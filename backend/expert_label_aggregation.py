def quadratic_weighted_kappa(
    ratings_a: np.ndarray,
    ratings_b: np.ndarray,
    *,
    min_rating: int = RATING_MIN,
    max_rating: int = RATING_MAX,
) -> float | None:
    """Calculate quadratic-weighted Cohen's kappa.

    Used pairwise between reviewers who rated common vendor-zone pairs.
    """

    a = np.asarray(
        ratings_a,
        dtype=int,
    )

    b = np.asarray(
        ratings_b,
        dtype=int,
    )


    if (
        len(
            a
        )
        != len(
            b
        )
    ):

        raise ValueError(
            "Rating arrays must have equal length"
        )


    if len(
        a
    ) == 0:

        return None


    categories = np.arange(
        min_rating,
        max_rating + 1,
    )


    category_count = len(
        categories
    )


    observed = np.zeros(
        (
            category_count,
            category_count,
        ),
        dtype=float,
    )


    for left, right in zip(
        a,
        b,
    ):

        if not (
            min_rating
            <= left
            <= max_rating
            and min_rating
            <= right
            <= max_rating
        ):

            raise ValueError(
                "Ratings outside permitted scale"
            )


        observed[
            left - min_rating,
            right - min_rating,
        ] += 1.0


    histogram_a = (
        observed.sum(
            axis=1
        )
    )

    histogram_b = (
        observed.sum(
            axis=0
        )
    )


    expected = np.outer(
        histogram_a,
        histogram_b,
    ) / float(
        len(
            a
        )
    )


    denominator_scale = float(
        (
            category_count
            - 1
        )
        ** 2
    )


    weights = np.zeros_like(
        observed
    )


    for i in range(
        category_count
    ):

        for j in range(
            category_count
        ):

            weights[
                i,
                j,
            ] = (
                (
                    i
                    - j
                )
                ** 2
            ) / denominator_scale


    observed_disagreement = float(
        np.sum(
            weights
            * observed
        )
    )


    expected_disagreement = float(
        np.sum(
            weights
            * expected
        )
    )


    if np.isclose(
        expected_disagreement,
        0.0,
    ):

        # If both reviewers are constant and agree on every common item,
        # agreement is perfect. Otherwise kappa is undefined.
        if np.array_equal(
            a,
            b,
        ):

            return 1.0

        return None


    return float(
        1.0
        - (
            observed_disagreement
            / expected_disagreement
        )
    )


def reviewer_agreement(
    labels: pd.DataFrame,
    *,
    min_common_pairs: int = 5,
) -> list[
    ReviewerAgreement
]:
    """Calculate pairwise reviewer agreement on numeric-rated pairs."""

    rated = labels.loc[
        labels[
            "_numeric_relevance"
        ].notna()
    ].copy()


    reviewers = sorted(
        rated[
            "reviewer_id"
        ].unique()
    )


    output: list[
        ReviewerAgreement
    ] = []


    for (
        reviewer_a,
        reviewer_b,

    ) in combinations(
        reviewers,
        2,
    ):

        left = (

            rated.loc[
                rated[
                    "reviewer_id"
                ].eq(
                    reviewer_a
                ),
                [
                    "pair_id",
                    "_numeric_relevance",
                ],
            ]

            .rename(
                columns={
                    "_numeric_relevance":
                        "rating_a"
                }
            )
        )


        right = (

            rated.loc[
                rated[
                    "reviewer_id"
                ].eq(
                    reviewer_b
                ),
                [
                    "pair_id",
                    "_numeric_relevance",
                ],
            ]

            .rename(
                columns={
                    "_numeric_relevance":
                        "rating_b"
                }
            )
        )


        common = left.merge(
            right,
            on="pair_id",
            how="inner",
            validate="one_to_one",
        )


        if (
            len(
                common
            )
            < min_common_pairs
        ):

            continue


        ratings_a = (
            common[
                "rating_a"
            ]
            .astype(int)
            .to_numpy()
        )


        ratings_b = (
            common[
                "rating_b"
            ]
            .astype(int)
            .to_numpy()
        )


        exact = float(
            np.mean(
                ratings_a
                == ratings_b
            )
        )


        kappa = (
            quadratic_weighted_kappa(
                ratings_a,
                ratings_b,
            )
        )


        output.append(
            ReviewerAgreement(

                reviewer_a=(
                    reviewer_a
                ),

                reviewer_b=(
                    reviewer_b
                ),

                common_rated_pairs=(
                    len(
                        common
                    )
                ),

                exact_agreement_rate=(
                    exact
                ),

                quadratic_weighted_kappa=(
                    kappa
                ),
            )
        )


    return output


