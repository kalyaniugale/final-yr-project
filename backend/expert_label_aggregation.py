"""Independent expert-label validation and aggregation.

This module prepares trustworthy expert-reviewed vendor-zone suitability labels
for later supervised ML experiments.

It consumes the files produced by:

    app/expert_review.py

Expected sources
----------------
reports/expert_review/review_queue.csv
reports/expert_review/expert_labels.csv

Outputs
-------
aggregated_expert_labels.csv
    Pair-level review quality, agreement and consensus information.

model_dataset.csv
    Leakage-controlled tabular dataset containing only READY_FOR_MODEL pairs.

expert_label_quality.json
    Audit report covering reviewer coverage, abstentions, disagreement,
    agreement and usable-label counts.

model_feature_manifest.json
    Explicit metadata/feature/target contract for the later training pipeline.

Important
---------
Expert labels are research judgements of suitability based on the evidence
shown to reviewers.

They are NOT:
- permits,
- observed vendor success,
- sales outcomes,
- demand measurements,
- live vacancy verification,
- or labels generated by the MCDA model.

The MCDA score and historical compatibility are deliberately excluded from the
training feature allow-list to reduce circular learning and label leakage.
"""

