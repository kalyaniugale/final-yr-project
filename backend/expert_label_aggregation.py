def _write_json_atomic(
    path: Path,
    payload: Mapping[
        str,
        Any,
    ],
) -> None:

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )


    temporary = (
        path.with_suffix(
            path.suffix
            + ".tmp"
        )
    )


    temporary.write_text(
        json.dumps(
            payload,
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )


    temporary.replace(
        path
    )


def _write_csv_atomic(
    path: Path,
    frame: pd.DataFrame,
) -> None:

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )


    temporary = (
        path.with_suffix(
            path.suffix
            + ".tmp"
        )
    )


    frame.to_csv(
        temporary,
        index=False,
        encoding="utf-8-sig",
    )


    temporary.replace(
        path
    )


