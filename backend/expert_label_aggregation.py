# ---------------------------------------------------------------------------
# Leakage-controlled ML dataset
# ---------------------------------------------------------------------------


def build_model_dataset(
    queue: pd.DataFrame,
    aggregated: pd.DataFrame,
) -> tuple[
    pd.DataFrame,
    dict[
        str,
        Any,
    ],
]:
    """Create the later supervised-learning dataset.

    Only fields explicitly allow-listed above may become model features.

    MCDA scores, MCDA ranks, historical business compatibility, reviewer
    identity, reasons, confidence, review decisions and IDs cannot
    accidentally become features.
    """

    ready = aggregated.loc[
        aggregated[
            "label_status"
        ].eq(
            "READY_FOR_MODEL"
        )
    ].copy()


    available_features = [

        field

        for field
        in MODEL_FEATURE_ALLOWLIST

        if field
        in queue.columns
    ]


    missing_configured_features = [

        field

        for field
        in MODEL_FEATURE_ALLOWLIST

        if field
        not in queue.columns
    ]


    queue_columns = list(
        dict.fromkeys(
            [
                *MODEL_METADATA_FIELDS,
                *available_features,
            ]
        )
    )


    evidence = queue[
        queue_columns
    ].copy()


    label_columns = [
        "pair_id",
        "target_relevance",
        "target_normalized",
        "rating_mean",
        "rating_median",
        "rating_std",
        "rating_range",
        "rated_count",
        "review_count",
        "abstain_count",
        "site_verification_count",
    ]


    dataset = evidence.merge(
        ready[
            label_columns
        ],
        on="pair_id",
        how="inner",
        validate="one_to_one",
    )


    # Numeric evidence is explicitly converted. Invalid textual values become
    # missing and will later be handled by the training preprocessing pipeline.
    for field in (
        NUMERIC_FEATURES
    ):

        if field in dataset.columns:

            dataset[
                field
            ] = pd.to_numeric(
                dataset[
                    field
                ],
                errors="coerce",
            )


    # Empty categorical values remain explicitly missing rather than becoming
    # misleading values such as zero.
    for field in (
        CATEGORICAL_FEATURES
    ):

        if field in dataset.columns:

            dataset[
                field
            ] = (
                dataset[
                    field
                ]
                .astype(str)
                .str.strip()
                .replace(
                    "",
                    pd.NA,
                )
            )


    # Targets are numeric and must always exist for READY rows.
    dataset[
        "target_relevance"
    ] = pd.to_numeric(
        dataset[
            "target_relevance"
        ],
        errors="raise",
    )


    dataset[
        "target_normalized"
    ] = pd.to_numeric(
        dataset[
            "target_normalized"
        ],
        errors="raise",
    )


    manifest = {
        "dataset_purpose":
            (
                "Experimental supervised learning of independent "
                "expert suitability judgments."
            ),

        "target":
            "target_relevance",

        "target_scale": {
            "minimum":
                RATING_MIN,

            "maximum":
                RATING_MAX,

            "meaning":
                (
                    "Median independent expert suitability rating "
                    "on the 0–4 ordinal scale."
                ),
        },

        "normalized_target":
            "target_normalized",

        "metadata_columns": [
            field
            for field
            in MODEL_METADATA_FIELDS
            if field
            in dataset.columns
        ],

        "categorical_features": [
            field
            for field
            in CATEGORICAL_FEATURES
            if field
            in dataset.columns
        ],

        "numeric_features": [
            field
            for field
            in NUMERIC_FEATURES
            if field
            in dataset.columns
        ],

        "feature_columns":
            available_features,

        "missing_configured_features":
            missing_configured_features,

        "audit_only_columns": [
            field
            for field
            in (
                "rating_mean",
                "rating_median",
                "rating_std",
                "rating_range",
                "rated_count",
                "review_count",
                "abstain_count",
                "site_verification_count",
            )
            if field
            in dataset.columns
        ],

        "explicitly_excluded_from_features": [
            "pair_id",
            "vendor_profile_id",
            "zone_id",
            "evidence_version",
            "reviewer_id",
            "reviewed_at_utc",
            "reason",
            "confidence",
            "recommendation",
            "relevance",
            "MCDA score",
            "MCDA ranking",
            "MCDA factor contributions",
            "historical business compatibility",
            "same-business historical count",
        ],

        "leakage_policy":
            (
                "Only feature_columns listed in this manifest may be "
                "supplied to the supervised model. Additional queue "
                "columns must not be automatically included."
            ),
    }


    ordered_columns = [

        *[
            field
            for field
            in MODEL_METADATA_FIELDS
            if field
            in dataset.columns
        ],

        *available_features,

        "target_relevance",
        "target_normalized",

        *[
            field
            for field
            in manifest[
                "audit_only_columns"
            ]
        ],
    ]


    dataset = dataset[
        list(
            dict.fromkeys(
                ordered_columns
            )
        )
    ]


    return (
        dataset,
        manifest,
    )


# ---------------------------------------------------------------------------
# Quality report
# ---------------------------------------------------------------------------


def build_quality_report(
    queue: pd.DataFrame,
    labels: pd.DataFrame,
    aggregated: pd.DataFrame,
    dataset: pd.DataFrame,
    manifest: Mapping[
        str,
        Any,
    ],
    *,
    config: AggregationConfig,
) -> dict[
    str,
    Any,
]:
    """Build an auditable label-quality report."""

    agreements = (
        reviewer_agreement(
            labels,
            min_common_pairs=(
                config
                .min_common_pairs_for_kappa
            ),
        )
    )


    valid_kappas = [
        item
        for item
        in agreements
        if (
            item.quadratic_weighted_kappa
            is not None
        )
    ]


    if valid_kappas:

        total_overlap = sum(
            item.common_rated_pairs
            for item
            in valid_kappas
        )


        weighted_kappa = float(

            sum(
                item.quadratic_weighted_kappa
                * item.common_rated_pairs
                for item
                in valid_kappas
            )

            / total_overlap
        )


        weighted_exact = float(

            sum(
                item.exact_agreement_rate
                * item.common_rated_pairs
                for item
                in valid_kappas
            )

            / total_overlap
        )


    else:

        weighted_kappa = None
        weighted_exact = None


    reviewer_rows: list[
        dict[
            str,
            Any,
        ]
    ] = []


    for reviewer_id in sorted(
        labels[
            "reviewer_id"
        ].unique()
    ):

        subset = labels.loc[
            labels[
                "reviewer_id"
            ].eq(
                reviewer_id
            )
        ]


        reviewer_rows.append(
            {
                "reviewer_id":
                    reviewer_id,

                "judgment_count":
                    int(
                        len(
                            subset
                        )
                    ),

                "numeric_rating_count":
                    int(
                        subset[
                            "_numeric_relevance"
                        ]
                        .notna()
                        .sum()
                    ),

                "abstain_count":
                    int(
                        subset[
                            "recommendation"
                        ]
                        .eq(
                            "Insufficient evidence / abstain"
                        )
                        .sum()
                    ),

                "site_verification_count":
                    int(
                        subset[
                            "recommendation"
                        ]
                        .eq(
                            "Requires site verification"
                        )
                        .sum()
                    ),
            }
        )


    status_counts = {
        str(
            key
        ):
            int(
                value
            )
        for key, value
        in aggregated[
            "label_status"
        ]
        .value_counts()
        .to_dict()
        .items()
    }


    rating_distribution = {

        str(
            rating
        ):
            int(
                (
                    labels[
                        "_numeric_relevance"
                    ]
                    == rating
                )
                .sum()
            )

        for rating
        in range(
            RATING_MIN,
            RATING_MAX + 1,
        )
    }


    recommendation_distribution = {
        str(
            key
        ):
            int(
                value
            )
        for key, value
        in labels[
            "recommendation"
        ]
        .value_counts()
        .to_dict()
        .items()
    }


    return {
        "generated_at_utc":
            datetime.now(
                timezone.utc
            ).isoformat(),

        "evaluation_type":
            "INDEPENDENT_EXPERT_LABEL_QUALITY",

        "queue_pair_count":
            int(
                len(
                    queue
                )
            ),

        "label_row_count":
            int(
                len(
                    labels
                )
            ),

        "reviewer_count":
            int(
                labels[
                    "reviewer_id"
                ].nunique()
            ),

        "ready_for_model_count":
            int(
                aggregated[
                    "label_status"
                ]
                .eq(
                    "READY_FOR_MODEL"
                )
                .sum()
            ),

        "model_dataset_row_count":
            int(
                len(
                    dataset
                )
            ),

        "quality_rules":
            asdict(
                config
            ),

        "label_status_counts":
            status_counts,

        "recommendation_distribution":
            recommendation_distribution,

        "rating_distribution":
            rating_distribution,

        "reviewer_summary":
            reviewer_rows,

        "reviewer_pair_agreement": [
            asdict(
                item
            )
            for item
            in agreements
        ],

        "agreement_summary": {
            "metric":
                (
                    "Pairwise quadratic-weighted Cohen kappa "
                    "on common numeric-rated pairs"
                ),

            "minimum_common_pairs":
                config.min_common_pairs_for_kappa,

            "eligible_reviewer_pairs":
                len(
                    agreements
                ),

            "weighted_mean_quadratic_kappa":
                weighted_kappa,

            "weighted_mean_exact_agreement":
                weighted_exact,
        },

        "model_features":
            manifest[
                "feature_columns"
            ],

        "missing_configured_features":
            manifest[
                "missing_configured_features"
            ],

        "target":
            manifest[
                "target"
            ],

        "limitations": [
            (
                "Expert suitability ratings are research judgments "
                "rather than observed business outcomes."
            ),
            (
                "Reviewer agreement does not establish predictive "
                "accuracy or municipal legality."
            ),
            (
                "Pairs requesting site verification are excluded from "
                "the model dataset by default."
            ),
            (
                "MCDA outputs and historical compatibility are excluded "
                "from supervised-model features to reduce circularity."
            ),
            (
                "Small expert samples may produce unstable agreement "
                "statistics and limited supervised-model generalization."
            ),
        ],
    }


