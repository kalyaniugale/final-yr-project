@dataclass(frozen=True)
class AggregationConfig:
    """Quality-control rules for expert label aggregation."""

    # Minimum independent numeric judgments required for a training label.
    min_raters: int = 3

    # Pair is considered highly disputed when its numeric ratings span more
    # than this many scale points.
    max_rating_range: int = 2

    # Additional dispersion threshold.
    max_rating_std: float = 1.0

    # A single explicit "Requires site verification" judgment blocks that pair
    # from the ML dataset until the evidence/site issue is resolved.
    exclude_if_site_verification_requested: bool = True

    # Reviewer-pair agreement is reported only when the two reviewers share at
    # least this many numeric-rated pairs.
    min_common_pairs_for_kappa: int = 5


@dataclass(frozen=True)
class ReviewerAgreement:
    """Agreement statistics for a pair of reviewers."""

    reviewer_a: str
    reviewer_b: str
    common_rated_pairs: int
    exact_agreement_rate: float
    quadratic_weighted_kappa: float | None


# ---------------------------------------------------------------------------
# Basic helpers
# ---------------------------------------------------------------------------


def _clean_text(
    value: Any,
) -> str:

    if value is None:
        return ""

    return str(
        value
    ).strip()


def _read_csv(
    path: str | Path,
    *,
    required: bool = True,
) -> pd.DataFrame:

    source = Path(
        path
    )

    if not source.exists():

        if required:

            raise FileNotFoundError(
                f"Required review file not found: {source}"
            )

        return pd.DataFrame()


    return pd.read_csv(
        source,
        dtype=str,
    ).fillna("")


def _validate_config(
    config: AggregationConfig,
) -> None:

    if config.min_raters < 1:

        raise ValueError(
            "min_raters must be at least 1"
        )


    if config.max_rating_range < 0:

        raise ValueError(
            "max_rating_range must be nonnegative"
        )


    if (
        not np.isfinite(
            config.max_rating_std
        )

        or config.max_rating_std < 0
    ):

        raise ValueError(
            "max_rating_std must be finite "
            "and nonnegative"
        )


    if (
        config.min_common_pairs_for_kappa
        < 1
    ):

        raise ValueError(
            "min_common_pairs_for_kappa "
            "must be at least 1"
        )


