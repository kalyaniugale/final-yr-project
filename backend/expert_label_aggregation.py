def _parse_relevance(
    value: Any,
) -> int:

    text = _clean_text(
        value
    )


    if not text:

        raise ValueError(
            "relevance is missing"
        )


    try:

        numeric = float(
            text
        )

    except ValueError as exc:

        raise ValueError(
            f"Invalid relevance rating: {value!r}"
        ) from exc


    if (
        not np.isfinite(
            numeric
        )

        or not float(
            numeric
        ).is_integer()
    ):

        raise ValueError(
            "relevance must be an integer "
            "from 0 to 4"
        )


    rating = int(
        numeric
    )


    if not (
        RATING_MIN
        <= rating
        <= RATING_MAX
    ):

        raise ValueError(
            "relevance must be between "
            f"{RATING_MIN} and {RATING_MAX}"
        )


    return rating


def validate_labels(
    labels: pd.DataFrame,
    queue: pd.DataFrame,
) -> pd.DataFrame:
    """Validate labels against the authoritative review queue."""

    missing = (
        set(
            LABEL_FIELDS
        )
        - set(
            labels.columns
        )
    )


    if missing:

        raise ValueError(
            "Expert label file is missing columns: "
            + ", ".join(
                sorted(
                    missing
                )
            )
        )


    result = labels.copy()


    for field in (
        LABEL_FIELDS
    ):

        result[
            field
        ] = (
            result[
                field
            ]
            .astype(str)
            .str.strip()
        )


    if result.empty:

        result[
            "_numeric_relevance"
        ] = pd.Series(
            dtype="Int64"
        )

        return result


    for field in (
        "pair_id",
        "reviewer_id",
        "recommendation",
        "confidence",
        "reason",
        "reviewed_at_utc",
        "evidence_version",
    ):

        if (
            result[
                field
            ]
            .eq("")
            .any()
        ):

            raise ValueError(
                f"Expert labels contain empty {field}"
            )


    # One independent judgment per reviewer per pair.
    duplicate_mask = (
        result.duplicated(
            subset=[
                "pair_id",
                "reviewer_id",
            ],
            keep=False,
        )
    )


    if duplicate_mask.any():

        duplicates = (

            result.loc[
                duplicate_mask,
                [
                    "pair_id",
                    "reviewer_id",
                ],
            ]

            .drop_duplicates()

            .to_dict(
                orient="records"
            )
        )

        raise ValueError(
            "Duplicate reviewer/pair judgments: "
            f"{duplicates}"
        )


    unknown_recommendations = sorted(

        set(
            result[
                "recommendation"
            ]
        )

        - RECOMMENDATION_VALUES
    )


    if unknown_recommendations:

        raise ValueError(
            "Unknown evidence decision values: "
            f"{unknown_recommendations}"
        )


    unknown_confidence = sorted(

        set(
            result[
                "confidence"
            ]
        )

        - CONFIDENCE_VALUES
    )


    if unknown_confidence:

        raise ValueError(
            "Unknown confidence values: "
            f"{unknown_confidence}"
        )


    queue_ids = set(
        queue[
            "pair_id"
        ]
    )


    unknown_pairs = sorted(

        set(
            result[
                "pair_id"
            ]
        )

        - queue_ids
    )


    if unknown_pairs:

        raise ValueError(
            "Labels reference pair IDs not present "
            f"in review queue: {unknown_pairs}"
        )


    # Validate timestamps rather than trusting arbitrary text.
    parsed_times = pd.to_datetime(
        result[
            "reviewed_at_utc"
        ],
        errors="coerce",
        utc=True,
    )


    if parsed_times.isna().any():

        bad = result.loc[
            parsed_times.isna(),
            "reviewed_at_utc",
        ].tolist()

        raise ValueError(
            "Invalid reviewed_at_utc values: "
            f"{bad}"
        )


    numeric_relevance: list[
        int | pd.NA
    ] = []


    for row in (
        result.itertuples(
            index=False
        )
    ):

        if (
            row.recommendation
            == "Sufficient evidence to rate"
        ):

            numeric_relevance.append(
                _parse_relevance(
                    row.relevance
                )
            )


        else:

            if _clean_text(
                row.relevance
            ):

                raise ValueError(
                    "relevance must be blank when "
                    f"recommendation={row.recommendation!r}"
                )


            numeric_relevance.append(
                pd.NA
            )


    result[
        "_numeric_relevance"
    ] = pd.array(
        numeric_relevance,
        dtype="Int64",
    )


    # -----------------------------------------------------------------------
    # Ensure saved review metadata still matches the authoritative queue row.
    # -----------------------------------------------------------------------

    queue_lookup = (
        queue.set_index(
            "pair_id",
            drop=False,
        )
    )


    metadata_fields = (
        "vendor_profile_id",
        "business_category",
        "preferred_division",
        "zone_id",
        "evidence_version",
    )


    mismatches: list[
        dict[
            str,
            str,
        ]
    ] = []


    for row in (
        result.itertuples(
            index=False
        )
    ):

        authoritative = (
            queue_lookup.loc[
                row.pair_id
            ]
        )


        for field in (
            metadata_fields
        ):

            label_value = _clean_text(
                getattr(
                    row,
                    field,
                )
            )

            queue_value = _clean_text(
                authoritative[
                    field
                ]
            )


            if (
                label_value
                != queue_value
            ):

                mismatches.append(
                    {
                        "pair_id":
                            row.pair_id,

                        "reviewer_id":
                            row.reviewer_id,

                        "field":
                            field,

                        "label_value":
                            label_value,

                        "queue_value":
                            queue_value,
                    }
                )


    if mismatches:

        raise ValueError(
            "Expert-label metadata does not match "
            "the review queue. First mismatches: "
            f"{mismatches[:10]}"
        )


    return result


