def validate_queue(
    queue: pd.DataFrame,
) -> pd.DataFrame:
    """Validate and normalize the review queue."""

    missing = (
        set(
            QUEUE_REQUIRED_FIELDS
        )
        - set(
            queue.columns
        )
    )


    if missing:

        raise ValueError(
            "Review queue is missing columns: "
            + ", ".join(
                sorted(
                    missing
                )
            )
        )


    result = queue.copy()


    for field in (
        QUEUE_REQUIRED_FIELDS
    ):

        result[
            field
        ] = (
            result[
                field
            ]
            .astype(str)
            .str.strip()
        )


    if (
        result[
            "pair_id"
        ]
        .eq("")
        .any()
    ):

        raise ValueError(
            "Review queue contains empty pair_id"
        )


    if (
        result[
            "pair_id"
        ]
        .duplicated()
        .any()
    ):

        duplicates = sorted(

            result.loc[
                result[
                    "pair_id"
                ].duplicated(
                    keep=False
                ),
                "pair_id",
            ].unique()
        )

        raise ValueError(
            "Review queue contains duplicate "
            f"pair_id values: {duplicates}"
        )


    for field in (
        "vendor_profile_id",
        "business_category",
        "zone_id",
        "evidence_version",
    ):

        if (
            result[
                field
            ]
            .eq("")
            .any()
        ):

            raise ValueError(
                f"Review queue contains empty {field}"
            )


    return result


