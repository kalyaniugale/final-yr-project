def ratio_text(
    value: float,
) -> str:
    """Represent exact synthetic Saaty ratios cleanly."""

    if np.isclose(
        value,
        1.0,
    ):

        return "1"


    if value > 1:

        return str(
            int(
                round(
                    value
                )
            )
        )


    reciprocal = int(
        round(
            1.0
            / value
        )
    )

    return (
        f"1/{reciprocal}"
    )


def generate_synthetic_ahp_reviews() -> pd.DataFrame:
    """Create three perfectly coherent but slightly different AHP reviewers.

    Latent importance levels use powers of two.

    Because every comparison comes from an underlying priority vector,
    each individual comparison matrix is internally consistent.

    The three reviewers intentionally disagree slightly about whether
    commercial surroundings or access deserves greater importance.
    """

    # 2 ** level produces exact pairwise ratios:
    #
    # 1, 2, 4, 1/2, 1/4
    #
    # which are all valid Saaty-scale values.

    expert_levels = {

        "SYNTHETIC_EXPERT_01": {
            "business": 2,
            "commercial": 1,
            "access": 1,
            "facilities": 1,
            "preference": 0,
            "historical": 0,
        },

        "SYNTHETIC_EXPERT_02": {
            "business": 2,
            "commercial": 2,
            "access": 1,
            "facilities": 1,
            "preference": 0,
            "historical": 0,
        },

        "SYNTHETIC_EXPERT_03": {
            "business": 2,
            "commercial": 1,
            "access": 2,
            "facilities": 1,
            "preference": 0,
            "historical": 0,
        },
    }


    rows: list[
        dict[
            str,
            Any,
        ]
    ] = []


    for (
        expert_id,
        levels,

    ) in expert_levels.items():

        priorities = {
            factor:
                float(
                    2
                    ** levels[
                        factor
                    ]
                )

            for factor
            in FACTOR_ORDER
        }


        for (
            factor_a,
            factor_b,

        ) in factor_pairs():

            ratio = (
                priorities[
                    factor_a
                ]
                / priorities[
                    factor_b
                ]
            )


            rows.append(
                {
                    "expert_id":
                        expert_id,

                    "factor_a":
                        factor_a,

                    "factor_a_label":
                        FACTOR_LABELS[
                            factor_a
                        ],

                    "factor_b":
                        factor_b,

                    "factor_b_label":
                        FACTOR_LABELS[
                            factor_b
                        ],

                    "comparison_value":
                        ratio_text(
                            ratio
                        ),

                    "reason":
                        (
                            "SYNTHETIC DEMO judgment generated "
                            "from a predefined internally consistent "
                            "priority vector. Not a real expert response."
                        ),
                }
            )


    frame = pd.DataFrame(
        rows
    )


    write_csv(
        SYNTHETIC_AHP_REVIEWS,
        frame,
    )


    return frame


