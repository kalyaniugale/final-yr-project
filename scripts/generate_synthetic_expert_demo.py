def numeric_series(
    frame: pd.DataFrame,
    column: str,
) -> pd.Series:
    """Safely obtain numeric evidence."""

    if column not in frame.columns:

        return pd.Series(
            np.nan,
            index=frame.index,
            dtype=float,
        )


    return pd.to_numeric(
        frame[
            column
        ],
        errors="coerce",
    )


def high_is_good(
    frame: pd.DataFrame,
    column: str,
) -> pd.Series:
    """Convert an evidence feature into a 0–1 rank percentile."""

    values = numeric_series(
        frame,
        column,
    )


    if values.notna().sum() == 0:

        return pd.Series(
            0.5,
            index=frame.index,
            dtype=float,
        )


    ranks = values.rank(
        method="average",
        pct=True,
    )


    return (
        ranks
        .fillna(
            0.5
        )
        .clip(
            0.0,
            1.0,
        )
    )


def low_is_good(
    frame: pd.DataFrame,
    column: str,
) -> pd.Series:
    """Rank a distance-like feature where smaller values are preferable."""

    return (
        1.0
        - high_is_good(
            frame,
            column,
        )
    )


def mean_component(
    *series: pd.Series,
) -> pd.Series:

    frame = pd.concat(
        series,
        axis=1,
    )


    return frame.mean(
        axis=1,
    )


def normalized_components(
    queue: pd.DataFrame,
) -> pd.DataFrame:
    """Construct synthetic evidence components.

    These use only evidence visible in app/expert_review.py.

    They intentionally do NOT use:
    - MCDA score,
    - MCDA factor score,
    - MCDA contribution,
    - rank,
    - historical business compatibility,
    - historical same-business count.
    """

    result = pd.DataFrame(
        index=queue.index
    )


    commercial_poi = high_is_good(
        queue,
        "commercial_poi_count_250m",
    )


    market_poi = high_is_good(
        queue,
        "market_poi_count_500m",
    )


    food_poi = high_is_good(
        queue,
        "food_poi_count_250m",
    )


    landuse = high_is_good(
        queue,
        "mapped_landuse_coverage_ratio_500m",
    )


    major_road = low_is_good(
        queue,
        "distance_to_major_road_m",
    )


    bus_distance = low_is_good(
        queue,
        "distance_to_bus_access_m",
    )


    bus_count = high_is_good(
        queue,
        "bus_count_500m",
    )


    healthcare = high_is_good(
        queue,
        "healthcare_count_500m",
    )


    education = high_is_good(
        queue,
        "education_count_500m",
    )


    toilet = high_is_good(
        queue,
        "toilet_count_500m",
    )


    parking = high_is_good(
        queue,
        "parking_count_500m",
    )


    result[
        "commercial_context"
    ] = mean_component(
        commercial_poi,
        market_poi,
        food_poi,
        landuse,
    )


    result[
        "access_context"
    ] = mean_component(
        major_road,
        bus_distance,
        bus_count,
    )


    result[
        "facility_context"
    ] = mean_component(
        healthcare,
        education,
        toilet,
        parking,
    )


    preferred = (
        queue.get(
            "preferred_division",
            pd.Series(
                "",
                index=queue.index,
            ),
        )
        .fillna("")
        .astype(str)
        .str.strip()
    )


    zone_division = (
        queue.get(
            "zone_division",
            pd.Series(
                "",
                index=queue.index,
            ),
        )
        .fillna("")
        .astype(str)
        .str.strip()
    )


    result[
        "preference_context"
    ] = np.where(
        preferred.eq(""),
        0.5,
        preferred.eq(
            zone_division
        ).astype(float),
    )


    # -----------------------------------------------------------------------
    # Business-context component
    # -----------------------------------------------------------------------

    business_values: list[
        float
    ] = []


    categories = (
        queue[
            "business_category"
        ]
        .fillna("")
        .astype(str)
        .str.lower()
    )


    for index, category in (
        categories.items()
    ):

        commercial_value = float(
            commercial_poi.loc[
                index
            ]
        )

        market_value = float(
            market_poi.loc[
                index
            ]
        )

        food_value = float(
            food_poi.loc[
                index
            ]
        )

        access_value = float(
            result.loc[
                index,
                "access_context",
            ]
        )


        if (
            "vegetable"
            in category
            or "fruit"
            in category
        ):

            value = (
                0.60
                * market_value
                + 0.25
                * commercial_value
                + 0.15
                * access_value
            )


        elif (
            "food"
            in category
        ):

            value = (
                0.55
                * food_value
                + 0.30
                * commercial_value
                + 0.15
                * access_value
            )


        elif (
            "cloth"
            in category
            or "retail"
            in category
        ):

            value = (
                0.65
                * commercial_value
                + 0.20
                * market_value
                + 0.15
                * access_value
            )


        elif (
            "service"
            in category
        ):

            value = (
                0.45
                * access_value
                + 0.40
                * commercial_value
                + 0.15
                * market_value
            )


        else:

            value = (
                0.45
                * commercial_value
                + 0.30
                * market_value
                + 0.25
                * access_value
            )


        business_values.append(
            float(
                np.clip(
                    value,
                    0.0,
                    1.0,
                )
            )
        )


    result[
        "business_context"
    ] = business_values


    # -----------------------------------------------------------------------
    # Evidence completeness
    # -----------------------------------------------------------------------

    visible_evidence_columns = [
        "official_capacity",
        "mapped_landuse_coverage_ratio_500m",
        "commercial_poi_count_250m",
        "market_poi_count_500m",
        "food_poi_count_250m",
        "distance_to_major_road_m",
        "distance_to_bus_access_m",
        "bus_count_500m",
        "healthcare_count_500m",
        "education_count_500m",
        "toilet_count_500m",
        "parking_count_500m",
    ]


    completeness_parts = []


    for column in (
        visible_evidence_columns
    ):

        if column in queue.columns:

            completeness_parts.append(
                numeric_series(
                    queue,
                    column,
                ).notna().astype(
                    float
                )
            )


    if completeness_parts:

        result[
            "evidence_completeness"
        ] = mean_component(
            *completeness_parts
        )


    else:

        result[
            "evidence_completeness"
        ] = 0.0


    # -----------------------------------------------------------------------
    # Synthetic latent suitability
    # -----------------------------------------------------------------------
    #
    # This is deliberately NOT identical to the production MCDA formula.
    #
    # It represents a hypothetical expert evidence interpretation.
    # -----------------------------------------------------------------------

    result[
        "latent_suitability"
    ] = (
        4.0
        * (
            0.30
            * result[
                "business_context"
            ]

            + 0.25
            * result[
                "commercial_context"
            ]

            + 0.20
            * result[
                "access_context"
            ]

            + 0.15
            * result[
                "facility_context"
            ]

            + 0.10
            * result[
                "preference_context"
            ]
        )
    ).clip(
        0.0,
        4.0,
    )


    return result


