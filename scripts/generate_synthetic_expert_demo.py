def confidence_level(
    completeness: float,
    noisy_score: float,
) -> str:

    if completeness < 0.65:

        return "Low"


    distance_from_middle = abs(
        noisy_score
        - 2.0
    )


    if (
        completeness >= 0.90
        and distance_from_middle >= 0.75
    ):

        return "High"


    return "Medium"


def generate_synthetic_labels(
    queue: pd.DataFrame,
) -> pd.DataFrame:
    """Generate four clearly-labelled synthetic reviewers."""

    rng = np.random.default_rng(
        RANDOM_SEED
    )


    components = normalized_components(
        queue
    )


    reviewers = [
        {
            "id":
                "SYNTHETIC_REVIEWER_01",

            "bias":
                -0.08,

            "noise":
                0.32,
        },
        {
            "id":
                "SYNTHETIC_REVIEWER_02",

            "bias":
                0.10,

            "noise":
                0.36,
        },
        {
            "id":
                "SYNTHETIC_REVIEWER_03",

            "bias":
                0.00,

            "noise":
                0.30,
        },
        {
            "id":
                "SYNTHETIC_REVIEWER_04",

            "bias":
                0.04,

            "noise":
                0.42,
        },
    ]


    rows: list[
        dict[
            str,
            Any,
        ]
    ] = []


    base_time = datetime.now(
        timezone.utc
    )


    review_counter = 0


    for index, queue_row in (
        queue.iterrows()
    ):

        latent = float(
            components.loc[
                index,
                "latent_suitability",
            ]
        )


        completeness = float(
            components.loc[
                index,
                "evidence_completeness",
            ]
        )


        geometry_status = str(
            queue_row.get(
                "geometry_status",
                "",
            )
            or ""
        ).lower()


        questionable_geometry = any(
            word in geometry_status

            for word
            in (
                "missing",
                "unusable",
                "uncertain",
                "low",
            )
        )


        for reviewer_index, reviewer in enumerate(
            reviewers
        ):

            review_counter += 1


            recommendation = (
                "Sufficient evidence to rate"
            )


            # The first three synthetic reviewers normally provide a rating,
            # guaranteeing enough independent labels for most pairs.
            #
            # The fourth reviewer demonstrates real-world abstention/site
            # verification behavior.

            if reviewer_index == 3:

                poor_evidence = (
                    completeness
                    < 0.70
                    or questionable_geometry
                )


                site_probability = (
                    0.10
                    if poor_evidence
                    else 0.02
                )


                abstain_probability = (
                    0.15
                    if poor_evidence
                    else 0.04
                )


                draw = float(
                    rng.random()
                )


                if (
                    draw
                    < site_probability
                ):

                    recommendation = (
                        "Requires site verification"
                    )


                elif (
                    draw
                    < (
                        site_probability
                        + abstain_probability
                    )
                ):

                    recommendation = (
                        "Insufficient evidence / abstain"
                    )


            noisy_score = (
                latent
                + float(
                    reviewer[
                        "bias"
                    ]
                )
                + float(
                    rng.normal(
                        0.0,
                        float(
                            reviewer[
                                "noise"
                            ]
                        ),
                    )
                )
            )


            noisy_score = float(
                np.clip(
                    noisy_score,
                    0.0,
                    4.0,
                )
            )


            if (
                recommendation
                == "Sufficient evidence to rate"
            ):

                relevance = int(
                    np.clip(
                        np.rint(
                            noisy_score
                        ),
                        0,
                        4,
                    )
                )


                confidence = confidence_level(
                    completeness,
                    noisy_score,
                )


                reason = (
                    "SYNTHETIC DEMO judgment generated from "
                    "business-context, commercial, access, "
                    "facility and preferred-division evidence "
                    "visible in the independent review interface. "
                    "No MCDA score or historical compatibility "
                    "was used."
                )


            elif (
                recommendation
                == "Requires site verification"
            ):

                relevance = ""


                confidence = "Low"


                reason = (
                    "SYNTHETIC DEMO site-verification flag "
                    "generated because the simulated reviewer "
                    "treated the available reference evidence "
                    "as insufficient for a reliable rating."
                )


            else:

                relevance = ""


                confidence = "Low"


                reason = (
                    "SYNTHETIC DEMO abstention generated to "
                    "represent an independent reviewer choosing "
                    "not to assign a suitability rating when "
                    "available evidence is limited."
                )


            reviewed_at = (
                base_time
                + timedelta(
                    seconds=review_counter
                )
            ).isoformat()


            rows.append(
                {
                    "pair_id":
                        str(
                            queue_row[
                                "pair_id"
                            ]
                        ),

                    "vendor_profile_id":
                        str(
                            queue_row[
                                "vendor_profile_id"
                            ]
                        ),

                    "business_category":
                        str(
                            queue_row[
                                "business_category"
                            ]
                        ),

                    "preferred_division":
                        str(
                            queue_row.get(
                                "preferred_division",
                                "",
                            )
                            or ""
                        ),

                    "zone_id":
                        str(
                            queue_row[
                                "zone_id"
                            ]
                        ),

                    "reviewer_id":
                        reviewer[
                            "id"
                        ],

                    "reviewed_at_utc":
                        reviewed_at,

                    "relevance":
                        relevance,

                    "recommendation":
                        recommendation,

                    "confidence":
                        confidence,

                    "reason":
                        reason,

                    "evidence_version":
                        str(
                            queue_row[
                                "evidence_version"
                            ]
                        ),
                }
            )


    labels = pd.DataFrame(
        rows
    )


    write_csv(
        SYNTHETIC_LABELS,
        labels,
    )


    return labels


