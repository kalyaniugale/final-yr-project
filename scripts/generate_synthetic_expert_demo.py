def main() -> None:

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )


    if not REAL_REVIEW_QUEUE.exists():

        raise FileNotFoundError(
            "Real review queue does not exist: "
            f"{REAL_REVIEW_QUEUE}"
        )


    queue = pd.read_csv(
        REAL_REVIEW_QUEUE,
        dtype=str,
    ).fillna("")


    if queue.empty:

        raise ValueError(
            "review_queue.csv contains no pairs"
        )


    required = {
        "pair_id",
        "vendor_profile_id",
        "business_category",
        "preferred_division",
        "zone_id",
        "evidence_version",
    }


    missing = (
        required
        - set(
            queue.columns
        )
    )


    if missing:

        raise ValueError(
            "review_queue.csv is missing required columns: "
            + ", ".join(
                sorted(
                    missing
                )
            )
        )


    # -----------------------------------------------------------------------
    # 1. Synthetic AHP
    # -----------------------------------------------------------------------

    generate_synthetic_ahp_reviews()


    ahp_result = (
        run_synthetic_ahp()
    )


    # -----------------------------------------------------------------------
    # 2. Synthetic expert suitability reviews
    # -----------------------------------------------------------------------

    labels = generate_synthetic_labels(
        queue
    )


    # -----------------------------------------------------------------------
    # 3. Real aggregation logic operating on synthetic labels
    # -----------------------------------------------------------------------

    prepared = (
        run_synthetic_label_aggregation()
    )


    # -----------------------------------------------------------------------
    # 4. Real grouped RF pipeline operating on synthetic labels
    # -----------------------------------------------------------------------

    training = (
        run_random_forest_demo(
            prepared
        )
    )


    # -----------------------------------------------------------------------
    # 5. Explicit synthetic-data audit manifest
    # -----------------------------------------------------------------------

    write_demo_manifest(
        queue=queue,
        ahp_result=ahp_result,
        labels=labels,
        prepared=prepared,
        training=training,
    )


    print_summary(
        queue,
        ahp_result,
        labels,
        prepared,
        training,
    )


if __name__ == "__main__":
    main()