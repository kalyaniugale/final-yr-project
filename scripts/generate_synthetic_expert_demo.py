def run_random_forest_demo(
    prepared,
):
    """Run grouped Random Forest validation on synthetic expert labels."""

    dataset = prepared[
        "model_dataset"
    ].copy()


    manifest = dict(
        prepared[
            "manifest"
        ]
    )


    if dataset.empty:

        return None


    vendor_groups = int(
        dataset[
            "vendor_profile_id"
        ].nunique()
    )


    zone_groups = int(
        dataset[
            "zone_id"
        ].nunique()
    )


    if vendor_groups >= 2:

        group_column = (
            "vendor_profile_id"
        )


        group_count = (
            vendor_groups
        )


    elif zone_groups >= 2:

        # Fallback only if the current review queue contains one vendor
        # profile. This is explicitly recorded in the report.

        group_column = (
            "zone_id"
        )


        group_count = (
            zone_groups
        )


    else:

        return None


    folds = min(
        5,
        group_count,
    )


    config = TrainingConfig(
        group_column=group_column,
        cv_folds=folds,
        random_seed=RANDOM_SEED,
        include_xgboost=False,
        random_forest_estimators=300,
        n_jobs=2,
    )


    training = train_models(
        dataset,
        manifest,
        config=config,
        dataset_sha256=None,
        feature_manifest_sha256=None,
        save_artifacts=False,
    )


    report = dict(
        training[
            "report"
        ]
    )


    report[
        "synthetic_demo"
    ] = True


    report[
        "real_expert_validation"
    ] = False


    report[
        "interpretation"
    ] = (
        "Proof-of-pipeline experiment using synthetic expert "
        "judgments. Metrics must not be reported as final "
        "real-world model performance."
    )


    baseline_mae = float(
        report[
            "baseline"
        ][
            "metrics"
        ][
            "mae"
        ]
    )


    rf_mae = float(
        report[
            "models"
        ][
            "random_forest"
        ][
            "metrics"
        ][
            "mae"
        ]
    )


    if baseline_mae > 0:

        report[
            "synthetic_mae_improvement_percent"
        ] = float(
            100.0
            * (
                baseline_mae
                - rf_mae
            )
            / baseline_mae
        )


    else:

        report[
            "synthetic_mae_improvement_percent"
        ] = None


    write_json(
        SYNTHETIC_MODEL_COMPARISON,
        report,
    )


    write_csv(
        SYNTHETIC_OOF_PREDICTIONS,
        training[
            "oof_predictions"
        ],
    )


    bundle = training[
        "bundles"
    ][
        "random_forest"
    ]


    bundle[
        "synthetic_demo"
    ] = True


    bundle[
        "production_use_allowed"
    ] = False


    joblib.dump(
        bundle,
        SYNTHETIC_RF_MODEL,
    )


    return training


